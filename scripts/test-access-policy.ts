import assert from 'node:assert/strict';
import { allowedApiRoles, canAccessAdminPage, residentWriteMatches, residentPropertyUpdateMatches } from '../src/lib/access-policy';
import { isSessionCurrent, SESSION_MAX_AGE_SECONDS } from '../src/lib/session-policy';
import { hashPassword, verifyPassword } from '../src/lib/passwords';
import { allowLoginAttempt } from '../src/lib/login-rate-limit';

assert.equal(canAccessAdminPage('RESIDENT', '/admin/billing'), false);
assert.equal(canAccessAdminPage('TREASURER', '/admin/security-gate'), false);
assert.equal(canAccessAdminPage('SECURITY', '/admin/security-gate'), true);
assert.equal(canAccessAdminPage('CHAIRMAN', '/admin/ledger'), true);
assert.ok(allowedApiRoles('/api/payments/verify', 'POST')?.includes('TREASURER'));
assert.ok(!allowedApiRoles('/api/payments/verify', 'POST')?.includes('RESIDENT'));
assert.ok(!allowedApiRoles('/api/users/update-password', 'POST')?.includes('SECRETARY'));
assert.equal(allowedApiRoles('/api/receipts/verify', 'GET'), null);
assert.equal(residentWriteMatches({ propertyId: 'home-a' }, { propertyId: 'home-a' }), true);
assert.equal(residentWriteMatches({ propertyId: 'home-b' }, { propertyId: 'home-a' }), false);
assert.equal(residentWriteMatches({ propertyId: 'home-a', propertyCode: 'B-01' }, { propertyId: 'home-a', propertyCode: 'A-01' }), false);
assert.equal(residentWriteMatches({}, { propertyId: 'home-a' }), false);
const home = { propertyId: 'home-a', propertyCode: 'A-01' };
assert.equal(residentPropertyUpdateMatches({ id: 'home-a' }, home), true);
assert.equal(residentPropertyUpdateMatches({ code: 'a-01' }, home), true);
assert.equal(residentPropertyUpdateMatches({ propertyCode: 'A-01' }, home), true);
assert.equal(residentPropertyUpdateMatches({ id: 'home-a', code: 'B-01' }, home), false);
assert.equal(residentPropertyUpdateMatches({ code: 'B-01', propertyCode: 'A-01' }, home), false);
assert.equal(residentPropertyUpdateMatches({ propertyId: 'home-a' }, home), false);
assert.equal(residentPropertyUpdateMatches({ id: null, propertyCode: 'A-01' }, home), false);
assert.equal(isSessionCurrent(undefined, 1000), false);
assert.equal(isSessionCurrent(NaN, 1000), false);
assert.equal(isSessionCurrent(1001, 1000), false);
assert.equal(isSessionCurrent(1000, 1000 + SESSION_MAX_AGE_SECONDS * 1000 - 1), true);
assert.equal(isSessionCurrent(1000, 1000 + SESSION_MAX_AGE_SECONDS * 1000), false);
const password = 'A private test passphrase';
const hash = hashPassword(password);
assert.notEqual(hash, password);
assert.ok(verifyPassword(password, hash));
for (const guess of ['1234', '123456', 'admin123', 'warga123', 'bendahara123', 'satpam123']) assert.equal(verifyPassword(guess, hash), false);
assert.equal(verifyPassword('wrong', 'legacy-exact'), false);
assert.equal(verifyPassword('legacy-exact', 'legacy-exact'), true);
assert.equal(verifyPassword(password, '$scrypt$malformed'), false);
for (let attempt = 0; attempt < 20; attempt++) assert.equal(allowLoginAttempt('fixture-limit', 1000), true);
assert.equal(allowLoginAttempt('fixture-limit', 1000), false);
assert.equal(allowLoginAttempt('fixture-limit', 601001), true);
console.log('PASS role policy, own-house boundaries, password hashing/no universal password, and bounded login attempts');
